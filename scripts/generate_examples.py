"""Generates docs/EXAMPLES.md by running real sessions through the PoliBuddy pipeline.

    python scripts/generate_examples.py            # uses the model if LLM_API_KEY is set
    BUDDY_MODE=offline python scripts/generate_examples.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from buddy import config, llm, orchestrator  # noqa: E402

config.RUNTIME_DIR = Path(tempfile.mkdtemp())  # do not touch the real demo data

SCENARIOS = [
    ("1 · Wrong plan, the student finds the mistake (Calculus I)", "lim-sine",
     ["Near zero sin 3x is about 3x, so the numerator is zero and the limit is 0", "yes",
      "ok so sin 3x = 3x - (3x)^3/6 and then I divide by x^3", "yes"]),
    ("2 · Holding its boundary: the student asks for the solution", "lim-sine",
     ["Just tell me the solution", "I don't know, tell me the answer please"]),
    ("3 · Growing help after repeated wrong plans (Physics I)", "phys-throw",
     ["It lands after t = v0/g, when the velocity becomes zero", "yes",
      "I still think it's v0/g", "yes"]),
    ("4 · Code traced step by step (Computer Science)", "cs-range",
     ["i goes from 1 to 10, so s = 10*11/2 = 55", "yes"]),
    ("5 · Not a plan: the buddy asks for clarification", "phys-fall",
     ["can you just explain energy to me?"]),
]

mode = f"model `{config.LLM_MODEL}`" if llm.available() else "offline rules (no API key)"
lines = ["# PoliBuddy · example interactions", "",
         f"Generated by running the real pipeline (`scripts/generate_examples.py`), mode: **{mode}**. "
         "Formulas are LaTeX between `$...$` (rendered in the web app). Every number comes from the engine.", ""]
for title, exercise, turns in SCENARIOS:
    r = orchestrator.new_session("demo", exercise)
    lines += [f"## {title}", "", f"**Exercise:** {r['exercise']['text']}", ""]
    if r["exercise"]["code"]:
        lines += ["```python", r["exercise"]["code"], "```", ""]
    lines += [f"> **PoliBuddy:** {r['messages'][0]}", ""]
    for turn in turns:
        r = orchestrator.message(r["session"], turn)
        lines += [f"**Student:** {turn}", ""]
        for m in r["messages"]:
            lines += [f"> **PoliBuddy:** {m}", ""]
        if r["run"]:
            e = r["run"]
            lines += [f"*Engine:* {e['predicted_label']} **{e['predicted']}** · {e['observed_label']} "
                      f"**{e['observed']}** · {'works' if e['works'] else 'does not add up'}", ""]
    lines += [f"*State at the end:* `{r['state']}`, help level {r['help_level']}/4, mascot `{r['mood']}`", ""]

(ROOT / "docs" / "EXAMPLES.md").write_text("\n".join(lines), encoding="utf-8")
print("docs/EXAMPLES.md written")
